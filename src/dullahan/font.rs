#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_atlas_dimensions_and_glyph_pixels() {
        let rgba = build_font_atlas_rgba();
        assert_eq!(rgba.len(), (ATLAS_W * ATLAS_H * 4) as usize);
        let (u0, v0, u1, v1) = glyph_uv('A');
        assert!(u0 >= 0.0 && u1 <= 1.0 && u1 > u0);
        assert!(v0 >= 0.0 && v1 <= 1.0 && v1 > v0);
        // 'A' has lit pixels in its cell
        let lit = rgba.chunks_exact(4).filter(|p| p[3] == 255).count();
        assert!(lit > 500);
    }
}
