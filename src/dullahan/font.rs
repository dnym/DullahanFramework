//! Built-in crisp 5x7 ASCII bitmap font (`32..=126`) packed into a 128x64 RGBA8 atlas.
//! Zero external font libraries (no FreeType/HarfBuzz) required.

pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;
pub const CELL_W: u32 = 8;
pub const CELL_H: u32 = 8;
pub const ATLAS_COLS: u32 = 16;
pub const ATLAS_ROWS: u32 = 6; // 96 slots: ASCII 32..=127
pub const ATLAS_W: u32 = ATLAS_COLS * CELL_W; // 128
pub const ATLAS_H: u32 = ATLAS_ROWS * CELL_H; // 48

/// Returns `(u0, v0, u1, v1)` UV rectangle inside the built-in font atlas for an ASCII char.
pub fn glyph_uv(ch: char) -> (f32, f32, f32, f32) {
    let code = if (32..=126).contains(&(ch as u32)) {
        (ch as u32) - 32
    } else {
        (b'?' - 32) as u32
    };
    let col = code % ATLAS_COLS;
    let row = code / ATLAS_COLS;
    let u0 = (col * CELL_W) as f32 / ATLAS_W as f32;
    let v0 = (row * CELL_H) as f32 / ATLAS_H as f32;
    let u1 = (col * CELL_W + GLYPH_W) as f32 / ATLAS_W as f32;
    let v1 = (row * CELL_H + GLYPH_H) as f32 / ATLAS_H as f32;
    (u0, v0, u1, v1)
}

/// Generates the `ATLAS_W x ATLAS_H` RGBA8 pixel data (white glyphs with alpha 255, transparent background).
pub fn build_font_atlas_rgba() -> Vec<u8> {
    let mut rgba = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];
    for (idx, rows) in FONT_5X7.iter().enumerate() {
        let col = (idx as u32) % ATLAS_COLS;
        let row = (idx as u32) / ATLAS_COLS;
        let ox = col * CELL_W;
        let oy = row * CELL_H;
        for (y, &bits) in rows.iter().enumerate() {
            for x in 0..5u32 {
                if (bits & (1 << (4 - x))) != 0 {
                    let px = ox + x;
                    let py = oy + y as u32;
                    let off = ((py * ATLAS_W + px) * 4) as usize;
                    rgba[off] = 255;
                    rgba[off + 1] = 255;
                    rgba[off + 2] = 255;
                    rgba[off + 3] = 255;
                }
            }
        }
    }
    rgba
}

